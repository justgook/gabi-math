// Language management
class LanguageManager {
    constructor() {
        this.currentLanguage = localStorage.getItem('language') || 'en';
        this.init();
    }

    init() {
        this.updateContent();
        this.addLanguageSwitcher();
    }

    setLanguage(lang) {
        this.currentLanguage = lang;
        localStorage.setItem('language', lang);
        this.updateContent();
        this.updateLanguageSwitcher();
    }

    updateContent() {
        const elements = document.querySelectorAll('[data-translate]');
        elements.forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[this.currentLanguage] && translations[this.currentLanguage][key]) {
                if (element.tagName === 'INPUT' && element.type === 'button') {
                    element.value = translations[this.currentLanguage][key];
                } else {
                    element.textContent = translations[this.currentLanguage][key];
                }
            }
        });

        // Update document language attribute
        document.documentElement.lang = this.currentLanguage;
    }

    addLanguageSwitcher() {
        const navControls = document.querySelector('.nav-controls');
        if (navControls && !document.querySelector('.language-switcher')) {
            const languageDiv = document.createElement('div');
            languageDiv.className = 'language-switcher';
            
            const languageSelect = document.createElement('select');
            languageSelect.className = 'language-select';
            languageSelect.innerHTML = `
                <option value="en" ${this.currentLanguage === 'en' ? 'selected' : ''}>🇺🇸 EN</option>
                <option value="lv" ${this.currentLanguage === 'lv' ? 'selected' : ''}>🇱🇻 LV</option>
            `;
            
            languageSelect.addEventListener('change', (e) => {
                this.setLanguage(e.target.value);
            });
            
            languageDiv.appendChild(languageSelect);
            navControls.insertBefore(languageDiv, navControls.firstChild);
        }
    }

    updateLanguageSwitcher() {
        const languageSelect = document.querySelector('.language-select');
        if (languageSelect) {
            languageSelect.value = this.currentLanguage;
        }
    }

    getCurrentLanguage() {
        return this.currentLanguage;
    }

    translate(key) {
        return translations[this.currentLanguage][key] || translations['en'][key] || key;
    }
}

